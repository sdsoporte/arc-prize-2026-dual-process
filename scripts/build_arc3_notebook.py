#!/usr/bin/env python3
"""Regenerate the ARC-AGI-3 submission notebook from committed sources.

The Kaggle kernel notebook ``notebooks/arc3_submission_kernel/submission.ipynb`` is the
only deployment artifact for the ARC-AGI-3 agent (the runner cell gates the real run
behind ``KAGGLE_IS_COMPETITION_RERUN``). It used to be assembled by hand, so it drifted
from ``src/`` and shipped a pre-fix, non-reproducible seed. This script removes the
hand-maintenance: the agent cell is copied byte-for-byte from
``src/arc3_spatial_memory_agent.py`` and the other four cells are carried here as
templates, so the whole notebook can be regenerated and verified.

Usage::

    python3 scripts/build_arc3_notebook.py            # write the notebook
    python3 scripts/build_arc3_notebook.py --check    # exit 0 iff on-disk == generated

The script is pure standard library so it runs under the system ``python3`` with no
third-party imports.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
AGENT_SOURCE_DEFAULT = REPO_ROOT / "src" / "arc3_spatial_memory_agent.py"
NOTEBOOK_DEFAULT = REPO_ROOT / "notebooks" / "arc3_submission_kernel" / "submission.ipynb"

