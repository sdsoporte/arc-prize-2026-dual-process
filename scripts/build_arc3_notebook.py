# Key order is significant: it is what ``json.dumps`` preserves and what keeps the
# regenerated file byte-identical to the committed notebook.
NOTEBOOK_METADATA = {
    "kernelspec": {
        "language": "python",
        "display_name": "Python 3",
        "name": "python3",
    },
    "language_info": {
        "name": "python",
        "mimetype": "text/x-python",
        "file_extension": ".py",
        "pygments_lexer": "ipython3",
    },
    "kaggle": {
        "accelerator": "nvidiaTeslaT4",
        "isInternetEnabled": False,
        "isGpuEnabled": True,
        "language": "python",
        "sourceType": "notebook",
    },
}


def agent_cell_source(agent_source: str) -> str:
    """Return the ``%%writefile`` cell whose body is the agent source, unchanged."""
    return f"{WRITEFILE_LINE}\n{agent_source}"


def build_notebook(agent_source: str) -> dict:
    """Build the notebook document as a plain dict in the committed key order."""
    code_cell = lambda source: {  # noqa: E731 - tiny local helper, mirrors nbformat defaults
        "cell_type": "code",
        "metadata": {"trusted": True},
        "outputs": [],
        "execution_count": None,
        "source": source,
    }
    return {
        "metadata": NOTEBOOK_METADATA,
        "nbformat_minor": 4,
        "nbformat": 4,
        "cells": [
            {"cell_type": "markdown", "metadata": {}, "source": HEADER_CELL_SOURCE},
            code_cell(CELL_1_SOURCE),
            code_cell(agent_cell_source(agent_source)),
            code_cell(CELL_3_SOURCE),
            code_cell(CELL_4_SOURCE),
        ],
    }


def render_notebook(notebook: dict) -> str:
    """Serialise the notebook exactly as the committed artifact stores it."""
    return json.dumps(notebook, indent=1)


def generate(agent_source_path: Path) -> str:
    """Read the agent source and return the full notebook text."""
    agent_source = Path(agent_source_path).read_text(encoding="utf-8")
    return render_notebook(build_notebook(agent_source))


def _cell_source(cell: dict) -> str:
    source = cell.get("source", "")
    if isinstance(source, list):  # tolerate nbformat's line-list form
        source = "".join(source)
    return source


def _clip(text: str, limit: int = 240) -> str:
    if len(text) <= limit:
        return text
    return f"{text[:limit]}… (+{len(text) - limit} chars)"


def describe_differences(actual: dict, expected: dict) -> list[str]:
    """Return a short, readable summary of how the on-disk notebook drifted."""
    lines: list[str] = []
    if actual.get("metadata") != expected.get("metadata"):
        lines.append("metadata differs")
    for key in ("nbformat", "nbformat_minor"):
        if actual.get(key) != expected.get(key):
            lines.append(
                f"{key}: on-disk={actual.get(key)!r} generated={expected.get(key)!r}"
            )

    actual_cells = actual.get("cells", [])
    expected_cells = expected.get("cells", [])
    if len(actual_cells) != len(expected_cells):
        lines.append(
            f"cell count: on-disk={len(actual_cells)} generated={len(expected_cells)}"
        )

    for index, (a_cell, e_cell) in enumerate(zip(actual_cells, expected_cells)):
        if a_cell == e_cell:
            continue
        if a_cell.get("cell_type") != e_cell.get("cell_type"):
            lines.append(
                f"cell {index}: cell_type on-disk={a_cell.get('cell_type')!r} "
                f"generated={e_cell.get('cell_type')!r}"
            )
            continue
        a_src = _cell_source(a_cell)
        e_src = _cell_source(e_cell)
        if a_src != e_src:
            lines.append(
                f"cell {index} source differs: on-disk {len(a_src.splitlines())} lines "
                f"vs generated {len(e_src.splitlines())} lines"
            )
            diff = list(
                difflib.unified_diff(
                    a_src.splitlines(),
                    e_src.splitlines(),
                    fromfile=f"on-disk cell {index}",
                    tofile=f"generated cell {index}",
                    lineterm="",
                )
            )
            for diff_line in diff[:24]:
                lines.append("  " + _clip(diff_line))
            if len(diff) > 24:
                lines.append(f"  … ({len(diff) - 24} more diff lines)")
        else:
            lines.append(f"cell {index}: non-source fields differ (metadata/outputs)")
    if not lines:
        lines.append("notebook JSON differs at an unrecognised level")
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate the ARC-AGI-3 submission notebook from committed sources."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare the on-disk notebook with the generated one; exit non-zero on drift",
    )
    parser.add_argument(
        "--notebook",
        type=Path,
        default=NOTEBOOK_DEFAULT,
        help="notebook path (default: %(default)s)",
    )
    parser.add_argument(
        "--agent-source",
        type=Path,
        default=AGENT_SOURCE_DEFAULT,
        help="agent source path (default: %(default)s)",
    )
    args = parser.parse_args(argv)

    try:
        generated = generate(args.agent_source)
    except OSError as exc:
        print(f"error: cannot read agent source {args.agent_source}: {exc}", file=sys.stderr)
        return 2

    if args.check:
        if not args.notebook.exists():
            print(f"error: notebook not found: {args.notebook}", file=sys.stderr)
            return 2
        actual_text = args.notebook.read_text(encoding="utf-8")
        if actual_text == generated:
            print(f"OK: {args.notebook} matches the generated notebook")
            return 0
        print(
            f"DRIFT: {args.notebook} differs from the generated notebook",
            file=sys.stderr,
        )
        try:
            actual_nb = json.loads(actual_text)
            expected_nb = json.loads(generated)
        except json.JSONDecodeError as exc:
            print(f"  on-disk notebook is not valid JSON: {exc}", file=sys.stderr)
            return 1
        for line in describe_differences(actual_nb, expected_nb):
            print("  " + line, file=sys.stderr)
        return 1

    args.notebook.parent.mkdir(parents=True, exist_ok=True)
    args.notebook.write_text(generated, encoding="utf-8")
    print(f"wrote {args.notebook} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
